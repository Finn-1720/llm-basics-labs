# ---------- 工具 ----------
def setp(p, text, keep=True):
    """替换段落文字，保留首个 run 的格式"""
    runs = p.runs
    if not runs:
        p.add_run(text); return
    runs[0].text = text
    for r in runs[1:]:
        r.text = ""


def addp(p, text):
    """在段落末尾追加一个 run（用于提示语之外的分行）"""
    p.add_run(text)


def fill(cell, text, bold=False, size=None):
    cell.text = ""
    para = cell.paragraphs[0]
    run = para.add_run(str(text))
    run.bold = bold
    if size: run.font.size = Pt(size)
    return para


def delp(p):
    el = p._element
    el.getparent().remove(el)


def put_image(cell, path, width_cm=15.5):
    cell.text = ""
    para = cell.paragraphs[0]
    para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    para.add_run().add_picture(path, width=Cm(width_cm))


def add_row(table, after=-1):
    """复制最后一行并追加（保留边框样式）"""
    src = table.rows[-1]._tr
    new = copy.deepcopy(src)
    src.addnext(new)
    return table.rows[-1]


