def clean(text):
    import re
    text = re.sub(r"\*\*([^*]*)\*\*", r"\1", text)   # 去 Markdown 粗体
    text = text.replace("`", "")                     # 去反引号（Word 不渲染代码样式）
    return text


def setp(p, text):
    text = clean(text)
    if not p.runs:
        p.add_run(text)
        return
    p.runs[0].text = text
    for r in p.runs[1:]:
        r.text = ""


def fill(cell, text):
    setp(cell.paragraphs[0], text)


def add_para_after(anchor, text):
    new_p = copy.deepcopy(anchor._p)
    anchor._p.addnext(new_p)
    np = Paragraph(new_p, anchor._parent)
    setp(np, text)
    return np


